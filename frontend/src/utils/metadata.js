export function pageDescription(title) {
  return PAGE_DESCRIPTIONS[title.replace(/ \| ری‌بوک$/, '')] || HOME_DESCRIPTION;
}

export function bookDescription(book) {
  return [`کتاب «${book.title}»`, book.author && `اثر ${book.author}`,
    book.category?.name && `در دسته ${book.category.name}`,
    book.status === 'sold' ? 'این نسخه فروخته شده است؛ نسخه‌های دیگر را در ری‌بوک ببینید.' : 'مشخصات این نسخه دست دوم را در ری‌بوک بررسی کنید.']
    .filter(Boolean).join('، ');
}

export function catalogDescription(category, chips = []) {
  const context = chips.map(chip => chip.label).join('، ');
  return `کتاب‌های دست دوم${category ? ` دسته «${category.name}»` : ''} را در ری‌بوک مرور کنید.${context ? ` فیلترهای انتخاب‌شده: ${context}.` : ' مشخصات نسخه‌ها را بررسی کنید و کتاب مورد نیازتان را پیدا کنید.'}`;
}
